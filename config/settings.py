def _env_bool(value: str | None, default: bool = False) -> bool:
    if value is None or value.strip() == '':
        return default
    return value.strip().lower() in ('1', 'true', 'yes', 'on')


def resolve_debug(env: Mapping[str, str]) -> bool:
    """Resolve DEBUG from environment variables, defaulting to False in production."""
    raw = env.get('DJANGO_DEBUG', env.get('DEBUG', ''))
    return _env_bool(raw, default=False)


def resolve_secret_key(env: Mapping[str, str], *, debug: bool) -> str:
    """Resolve DJANGO_SECRET_KEY and reject missing or weak keys in production."""
    secret_key = env.get('DJANGO_SECRET_KEY', '').strip()
    if not secret_key:
        raise ImproperlyConfigured(
            'DJANGO_SECRET_KEY environment variable is required and must not be empty.'
        )
    if not debug and (
        secret_key.startswith('django-insecure-')
        or secret_key == 'replace-with-a-secure-random-50-character-secret-key'
        or len(secret_key) < 32
    ):
        raise ImproperlyConfigured(
            'Production deployments (DEBUG=False) require a strong DJANGO_SECRET_KEY.'
        )
    return secret_key


def resolve_allowed_hosts(env: Mapping[str, str], *, debug: bool) -> list[str]:
    """Resolve ALLOWED_HOSTS from environment variables."""
    raw_hosts = env.get('DJANGO_ALLOWED_HOSTS', env.get('ALLOWED_HOSTS', ''))
    hosts = [h.strip() for h in raw_hosts.split(',') if h.strip()]
    if not hosts:
        if debug:
            return ['localhost', '127.0.0.1', '10.0.2.2', '[::1]', 'testserver']
        raise ImproperlyConfigured(
            'DJANGO_ALLOWED_HOSTS must be configured when DEBUG=False.'
        )
    return hosts


def resolve_database_config(env: Mapping[str, str]) -> dict[str, str]:
    """Resolve PostgreSQL database configuration from DATABASE_URL or DB_* env vars."""
    database_url = env.get('DATABASE_URL', '').strip()
    if database_url:
        parsed = urlparse(database_url)
        scheme = parsed.scheme.lower()
        if scheme not in ('postgres', 'postgresql', 'pgsql'):
            raise ImproperlyConfigured(f'Unsupported DATABASE_URL scheme: {scheme}')
        db_name = unquote(parsed.path.lstrip('/'))
        db_user = unquote(parsed.username or '')
        db_password = unquote(parsed.password or '')
        if not db_name or not db_user or not db_password:
            raise ImproperlyConfigured(
                'DATABASE_URL must include database name, username, and password.'
            )
        return {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': db_name,
            'USER': db_user,
            'PASSWORD': db_password,
            'HOST': parsed.hostname or 'localhost',
            'PORT': str(parsed.port or 5432),
        }

    db_engine = env.get('DB_ENGINE', 'django.db.backends.postgresql').strip()
    db_name = env.get('DB_NAME', '').strip()
    db_user = env.get('DB_USER', '').strip()
    db_password = env.get('DB_PASSWORD', '').strip()
    db_host = env.get('DB_HOST', 'localhost').strip()
    db_port = env.get('DB_PORT', '5432').strip()

    if not db_name or not db_user or not db_password:
        raise ImproperlyConfigured(
            'Database credentials must be provided via DATABASE_URL or '
            'DB_NAME, DB_USER, and DB_PASSWORD environment variables.'
        )

    return {
        'ENGINE': db_engine,
        'NAME': db_name,
        'USER': db_user,
        'PASSWORD': db_password,
        'HOST': db_host,
        'PORT': db_port,
    }


def resolve_channel_layers(env: Mapping[str, str], *, debug: bool) -> dict:
    """
    Resolve CHANNEL_LAYERS configuration:
    - Use RedisChannelLayer when REDIS_URL is configured.
    - Use InMemoryChannelLayer for local development only (DEBUG=True).
    - In production (DEBUG=False), fail with ImproperlyConfigured if REDIS_URL is missing.
    """
    redis_url = env.get('REDIS_URL', '').strip()
    if redis_url:
        return {
            'default': {
                'BACKEND': 'channels_redis.core.RedisChannelLayer',
                'CONFIG': {
                    'hosts': [redis_url],
                },
            },
        }
    if debug:
        return {
            'default': {
                'BACKEND': 'channels.layers.InMemoryChannelLayer',
            },
        }
    raise ImproperlyConfigured(
        'REDIS_URL environment variable is required when DEBUG=False for production Django Channels.'
    )


def build_middleware(has_whitenoise: bool | None = None) -> list[str]:
    """
    Build MIDDLEWARE list with WhiteNoiseMiddleware placed immediately after
    SecurityMiddleware when installed.
    """
    if has_whitenoise is None:
        has_whitenoise = importlib.util.find_spec('whitenoise') is not None
    middleware = [
        'django.middleware.security.SecurityMiddleware',
    ]
    if has_whitenoise:
        middleware.append('whitenoise.middleware.WhiteNoiseMiddleware')
    middleware.extend([
        'corsheaders.middleware.CorsMiddleware',
        'django.contrib.sessions.middleware.SessionMiddleware',
        'django.middleware.common.CommonMiddleware',
        'django.middleware.csrf.CsrfViewMiddleware',
        'django.contrib.auth.middleware.AuthenticationMiddleware',
        'django.contrib.messages.middleware.MessageMiddleware',
        'django.middleware.clickjacking.XFrameOptionsMiddleware',
    ])
    return middleware


def resolve_csrf_trusted_origins(env: Mapping[str, str], *, debug: bool) -> list[str]:
    """Resolve CSRF_TRUSTED_ORIGINS from environment variable."""
    raw_csrf = env.get('CSRF_TRUSTED_ORIGINS', '')
    origins = [origin.strip() for origin in raw_csrf.split(',') if origin.strip()]
    if debug and not origins:
        return [
            'http://localhost:3000',
            'http://127.0.0.1:3000',
            'http://localhost:8000',
            'http://127.0.0.1:8000',
            'http://localhost:8080',
            'http://127.0.0.1:8080',
            'http://localhost:55900',
            'http://127.0.0.1:55900',
        ]
    return origins


def resolve_production_security_settings(
    env: Mapping[str, str], *, debug: bool
) -> dict[str, object]:
    """Resolve HTTPS proxy header, SSL redirect, and secure cookie settings."""
    if debug:
        return {
            'SECURE_PROXY_SSL_HEADER': None,
            'SECURE_SSL_REDIRECT': False,
            'SESSION_COOKIE_SECURE': False,
            'CSRF_COOKIE_SECURE': False,
        }
    return {
        'SECURE_PROXY_SSL_HEADER': ('HTTP_X_FORWARDED_PROTO', 'https'),
        'SECURE_SSL_REDIRECT': _env_bool(env.get('DJANGO_SECURE_SSL_REDIRECT'), default=True),
        'SESSION_COOKIE_SECURE': _env_bool(env.get('DJANGO_SESSION_COOKIE_SECURE'), default=True),
        'CSRF_COOKIE_SECURE': _env_bool(env.get('DJANGO_CSRF_COOKIE_SECURE'), default=True),
    }


